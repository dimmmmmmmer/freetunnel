package org.freetunnel.android;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertSame;

import org.junit.Test;

import java.util.Arrays;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

public final class TomlLinesTest {
    // The paths RoutingConfig takes a subscription address out of.
    private static final Set<List<String>> SUBSCRIPTION = new HashSet<>(Arrays.asList(
            Arrays.asList("subscription_url"), Arrays.asList("endpoint", "subscription"),
            Arrays.asList("endpoint", "subscription_url")));
    private static final String URL = "\"https://alice:s3cret@vpn.example.com/subscription\"";

    private static String without(String toml) { return TomlLines.without(toml, SUBSCRIPTION); }

    // TrustTunnel endpoint 1.3's export, pasted under [endpoint] as its first line
    // says, with its comments and a certificate it writes over several lines.
    private static final String EXPORT = "[endpoint]\n"
            + "# This file was automatically generated by endpoint and could be used in vpn client.\n"
            + "\n"
            + "# Endpoint host name, used for TLS session establishment\n"
            + "hostname = \"vpn.example.com\"\n"
            + "\n"
            + "# Endpoint addresses.\n"
            + "addresses = [\"1.2.3.4:443\"]\n"
            + "username = \"alice\"\n"
            + "password = \"s3cret\"\n"
            + "client_random_auth_key = \"\"\n"
            + "certificate = \"\"\"\n"
            + "-----BEGIN CERTIFICATE-----\n"
            + "MIIBszCCAVmgAwIBAgIUQ0FGRQ==\n"
            + "-----END CERTIFICATE-----\n"
            + "\"\"\"\n"
            + "upstream_protocol = \"http2\"\n";
    private static final String TUN = "\n[listener.tun]\nincluded_routes = [\"0.0.0.0/0\"]\nmtu_size = 1500\n";

    @Test public void takesOutOnlyTheSubscriptionLine() {
        String expected = EXPORT + TUN;
        // Where the endpoint's export puts it: last, then under [endpoint] once pasted.
        assertEquals(expected, without(EXPORT + "subscription_url = " + URL + "\n" + TUN));
        // At the top, before any table.
        assertEquals(expected, without("subscription_url = " + URL + "\n" + EXPORT + TUN));
        // Spelled any way TOML allows on one line.
        for (String line : new String[]{
                "\"subscription_url\" = " + URL, "'subscription_url' = " + URL, "  subscription_url=" + URL + " # note",
                "subscription.url = " + URL, "subscription = { url = " + URL + ", interval = 3600 }",
                "subscription . \"url\" = " + URL}) {
            assertEquals(line, expected, without(EXPORT + line + "\n" + TUN));
        }
        // A dotted key at the top, which is the same table to the core.
        assertEquals(TUN, without("endpoint.subscription.url = " + URL + "\n" + TUN));
    }

    @Test public void takesOutTheWholeSubscriptionTable() {
        // Its header, keys and comments go; the blank lines around it stay.
        String table = "\n[endpoint.subscription]\n# Refreshed by the client\nurl = " + URL + "\ninterval = 3600\n";
        assertEquals(EXPORT + "\n" + TUN, without(EXPORT + table + TUN));
        // An empty one too, which names a subscription all the same.
        assertEquals(EXPORT + TUN, without(EXPORT + "\n[endpoint.subscription]" + TUN));
        // An array of them, and tables inside it, go too.
        assertEquals(EXPORT + "\n" + TUN, without(EXPORT + "\n[[endpoint.subscription]]\nurl = " + URL
                + "\n[endpoint.subscription.extra]\nkey = 1\n" + TUN));
        // Blank lines and comments just before the next table are about that table.
        assertEquals(EXPORT + "\n# TUN settings\n[listener.tun]\nmtu_size = 1500\n",
                without(EXPORT + "[endpoint.subscription]\nurl = " + URL + "\n\n# TUN settings\n[listener.tun]\nmtu_size = 1500\n"));
        // At the end of the file, they go with the table.
        assertEquals(EXPORT, without(EXPORT + "[ endpoint . \"subscription\" ]  # the client's\nurl = " + URL + "\n\n# end\n"));
    }

    @Test public void valuesOverSeveralLinesGoWhole() {
        String expected = EXPORT + TUN;
        assertEquals(expected, without(EXPORT + "subscription_url = \"\"\"\n" + URL.replace("\"", "") + "\n\"\"\"\n" + TUN));
        assertEquals(expected, without(EXPORT + "subscription_url = '''\n[endpoint]\n'''\n" + TUN));
        assertEquals(expected, without(EXPORT + "subscription = [\n  " + URL + ", # first\n  \"]\",\n]\n" + TUN));
        // Up to two quotes before the closing three belong to the string.
        assertEquals(expected, without(EXPORT + "subscription_url = \"\"\"a\n\"b\"\"\"\"\"\n" + TUN));
        assertEquals(expected, without(EXPORT + "subscription_url = \"\"\"a\"\"\"\"\n" + TUN));
        // An escaped quote does not close one.
        assertEquals(expected, without(EXPORT + "subscription_url = \"\"\"a\\\"\"\"\nb\"\"\"\n" + TUN));
    }

    @Test public void keepsWhatOnlyLooksLikeASubscription() {
        String text = "subscription_url_note = 1\n" + EXPORT
                + "subscription_note = \"kept\"\n"
                + "quoted = \"say \\\"hi\" # and a comment\n"
                + "notes = \"\"\"\nsubscription_url = " + URL.replace("\"", "'") + "\n[endpoint.subscription]\n\"\"\"\n"
                + "addresses_extra = [\n  \"1.2.3.4:443\", # a [ bracket\n  '#',\n]\n"
                + "\n[extra]\nsubscription = \"not the endpoint's\"\nsubscription_url = 2\n"
                + "[endpoint_backup]\nsubscription_url = 3\n[[servers]]\nname = 'one'\n";
        assertEquals(text, without(text));
        // So does a subscription inside an inline [endpoint] table; RoutingConfig
        // finds it there by comparing with the parsed file.
        String inline = "endpoint = { hostname = \"h\", subscription_url = " + URL + " }\n";
        assertEquals(inline, without(inline));
    }

    @Test public void keepsLineEndingsAsTheyWere() {
        String crlf = (EXPORT + TUN).replace("\n", "\r\n");
        assertEquals(crlf, without(crlf.replace("upstream_protocol", "subscription_url = " + URL + "\r\nupstream_protocol")));
        // The last line need not end with a line break, the removed one included.
        assertEquals("[endpoint]\nhostname = \"h\"\n", without("[endpoint]\nhostname = \"h\"\nsubscription_url = " + URL));
        assertEquals("[endpoint]\nsubscription_note = 1", without("[endpoint]\nsubscription_url = " + URL + "\nsubscription_note = 1"));
    }

    private static final List<String> CERTIFICATE = Arrays.asList("endpoint", "certificate");
    private static final String NEW_VALUE = "\"\"\"\n-----BEGIN CERTIFICATE-----\nMAswAgUAMAIFAAMBAA==\n-----END CERTIFICATE-----\n\"\"\"";

    private static String replaced(String toml) {
        return TomlLines.edit(toml, SUBSCRIPTION, Collections.singletonMap(CERTIFICATE, NEW_VALUE));
    }

    @Test public void editGivesAKeyANewValue() {
        // The certificate's lines go, however many, and the new value takes their place
        // after the key as it was written. Everything else stays.
        String before = EXPORT.substring(0, EXPORT.indexOf("certificate = "));
        String after = EXPORT.substring(EXPORT.indexOf("upstream_protocol"));
        String expected = before + "certificate = " + NEW_VALUE + "\n" + after + TUN;
        assertEquals(expected, replaced(EXPORT + TUN));
        // A subscription goes at the same time.
        assertEquals(expected, replaced(EXPORT + "subscription_url = " + URL + "\n" + TUN));
        // On one line, with a comment after it, and spelled with a quoted key.
        for (String line : new String[]{"certificate = \"\"", "certificate='x' # pinned", "\"certificate\" = \"a\\nb\""}) {
            String key = line.substring(0, line.indexOf('=') + 1);
            assertEquals(line, "[endpoint]\n" + key + " " + NEW_VALUE + "\nhostname = \"h\"\n",
                    replaced("[endpoint]\n" + line + "\nhostname = \"h\"\n"));
        }
        // A dotted key at the top keeps naming [endpoint].
        assertEquals("endpoint.hostname = \"h\"\nendpoint . certificate = " + NEW_VALUE + "\n" + TUN,
                replaced("endpoint.hostname = \"h\"\nendpoint . certificate = '''\nold\n'''\n" + TUN));
        // The line keeps its own line ending, and the last line need not have one.
        String crlf = (EXPORT + TUN).replace("\n", "\r\n");
        assertEquals(crlf.replace(EXPORT.substring(EXPORT.indexOf("certificate = "), EXPORT.indexOf("upstream_protocol"))
                .replace("\n", "\r\n"), "certificate = " + NEW_VALUE + "\r\n"), replaced(crlf));
        assertEquals("[endpoint]\ncertificate = " + NEW_VALUE, replaced("[endpoint]\ncertificate = \"x\""));
    }

    @Test public void editLeavesWhatItDoesNotName() {
        // No such key: the text itself comes back.
        String text = "[endpoint]\nhostname = \"h\"\n[other]\ncertificate = \"x\"\n";
        assertSame(text, replaced(text));
        // A key of that name elsewhere, or deeper, is not the one named.
        String deeper = "[endpoint.extra]\ncertificate = \"x\"\n";
        assertSame(deeper, replaced(deeper));
        // Inside a table that is dropped, the key goes with the table.
        assertEquals("[endpoint]\nhostname = \"h\"\n",
                TomlLines.edit("[endpoint]\nhostname = \"h\"\n[endpoint.subscription]\ncertificate = \"x\"\n", SUBSCRIPTION,
                        Collections.singletonMap(Arrays.asList("endpoint", "subscription", "certificate"), NEW_VALUE)));
        // And what it cannot read, it still gives up on.
        assertNull(replaced("[endpoint]\ncertificate = \"\"\"\nnever closed\n"));
    }

    @Test public void givesUpOnWhatItCannotRead() {
        // A quoted key with an escape: it would have to be decoded to be named.
        assertNull(without(EXPORT + "\"subscription\\u005furl\" = " + URL + "\n"));
        // Not TOML, which the caller never hands it, but no wrong answer either.
        for (String broken : new String[]{"[endpoint\n", "[endpoint] x\n", "= 1\n", "a = \"open\n", "a = ]\n",
                "a = \"\"\"\nnever closed\n", "a = [1,\n", "a 1\n", "[endpoint]\nb = 'x\n"}) {
            assertNull(broken, without(broken));
        }
    }
}
