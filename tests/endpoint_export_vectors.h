// The TOML file a TrustTunnel endpoint exports for a client, shared by the tests
// of its import (parseEndpointExport, prepareEndpointExportImport and the file
// import), so each is checked against the same text.
//
// Laid out as the endpoint's compose_toml() fills in its TEMPLATE
// (lib/src/client_config.rs, endpoint v1.3.0-beta.2): every key at the top with
// no table, each under the comment the template gives it, and subscription_url
// added at the end when subscriptions are on. Written from that source, not taken
// from a running endpoint.

#include <QString>

#include "certificate_vectors.h"

namespace endpoint_export {

// A value with line breaks in it, as toml_edit writes one: a multi-line basic
// string opened on the key's line.
inline QString multiline(const QString &value)
{
    return QStringLiteral("\"\"\"\n") + value + QStringLiteral("\"\"\"");
}

// A PEM read with CRLF line endings, which toml_edit writes as a single-line basic
// string with the line breaks escaped.
inline QString singleLineCrlf(const QString &pem)
{
    QString escaped = pem;
    escaped.replace(QLatin1Char('\n'), QStringLiteral("\\r\\n"));
    return QLatin1Char('"') + escaped + QLatin1Char('"');
}

// What a test changes, one at a time. Strings are the values as the user would
// see them, but for the lists and the certificate, which are the TOML as written.
struct Fields {
    QString hostname = QStringLiteral("vpn.example.com");
    QString addresses = QStringLiteral("\"203.0.113.5:443\", \"[2001:db8::5]:443\"");
    QString customSni;
    bool hasIpv6 = true;
    QString username = QStringLiteral("alice");
    QString password = QStringLiteral("s3cret");
    QString clientRandomPrefix = QStringLiteral("aabbcc/ff00ff");
    QString clientRandomAuthKey; // the endpoint writes "" for a server without one
    bool skipVerification = false;
    QString certificate = multiline(certs::kLeafPem); // "\"\"" for a system-verifiable one
    QString upstreamProtocol = QStringLiteral("http3");
    bool antiDpi = true;
    QString name = QStringLiteral("Work VPN"); // the endpoint writes "" when it has none
    QString dnsUpstreams = QStringLiteral("\"1.1.1.1\", \"tls://dns.example.com\"");
    QString subscriptionUrl = QStringLiteral("https://alice:s3cret@vpn.example.com/subscription"); // "": off
};

inline QString flag(bool on)
{
    return on ? QStringLiteral("true") : QStringLiteral("false");
}

inline QString text(const Fields &f = Fields())
{
    QString t = QStringLiteral(
            "\n# This file was automatically generated by endpoint and could be used in vpn client.\n\n");
    t += QStringLiteral("# Endpoint host name, used for TLS session establishment\n"
                        "hostname = \"%1\"\n\n")
                 .arg(f.hostname);
    t += QStringLiteral("# Endpoint addresses in `IP:port` or `hostname:port` format\n"
                        "addresses = [%1]\n\n")
                 .arg(f.addresses);
    t += QStringLiteral("# Custom SNI value for TLS handshake.\n"
                        "# If set, this value is used as the TLS SNI instead of the hostname.\n"
                        "custom_sni = \"%1\"\n\n")
                 .arg(f.customSni);
    t += QStringLiteral("# Whether IPv6 traffic can be routed through the endpoint\n"
                        "has_ipv6 = %1\n\n")
                 .arg(flag(f.hasIpv6));
    t += QStringLiteral("# Username for authorization\n"
                        "username = \"%1\"\n\n")
                 .arg(f.username);
    t += QStringLiteral("# Password for authorization\n"
                        "password = \"%1\"\n\n")
                 .arg(f.password);
    t += QStringLiteral("# TLS client random hex prefix for connection filtering.\n"
                        "# Must have a corresponding rule in rules.toml.\n"
                        "client_random_prefix = \"%1\"\n\n")
                 .arg(f.clientRandomPrefix);
    t += QStringLiteral("# TLS client random auth key (hex string for HKDF+AES client_random derivation).\n"
                        "# Must have a corresponding rule with client_random_auth_key in rules.toml.\n"
                        "client_random_auth_key = \"%1\"\n\n")
                 .arg(f.clientRandomAuthKey);
    t += QStringLiteral("# Skip the endpoint certificate verification?\n"
                        "# That is, any certificate is accepted with this one set to true.\n"
                        "skip_verification = %1\n\n")
                 .arg(flag(f.skipVerification));
    t += QStringLiteral("# Endpoint certificate in PEM format.\n"
                        "# If not specified, the endpoint certificate is verified using the system storage.\n"
                        "certificate = %1\n\n")
                 .arg(f.certificate);
    t += QStringLiteral("# Protocol to be used to communicate with the endpoint [http2, http3]\n"
                        "upstream_protocol = \"%1\"\n\n")
                 .arg(f.upstreamProtocol);
    t += QStringLiteral("# Is anti-DPI measures should be enabled\n"
                        "anti_dpi = %1\n\n")
                 .arg(flag(f.antiDpi));
    t += QStringLiteral("# Human-readable server display name\n"
                        "name = \"%1\"\n\n")
                 .arg(f.name);
    t += QStringLiteral("# DNS upstreams to use when connected to this endpoint\n"
                        "dns_upstreams = [%1]\n")
                 .arg(f.dnsUpstreams);
    if (!f.subscriptionUrl.isEmpty())
        t += QStringLiteral("subscription_url = \"%1\"\n").arg(f.subscriptionUrl);
    return t;
}

} // namespace endpoint_export
